"""Generate five original style demonstrations; figures/tables are external PNGs.

Requires the project's qa extra (Pillow), local Node, and Arial font files.
No network, stock media, copied slides, or native PPT charts/tables are used.
"""
import argparse
import html
import json
from pathlib import Path
import subprocess
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SCALE = 3


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir', type=Path, required=True,
                        help='Directory containing Arial.ttf and Arial Bold.ttf; fonts are not redistributed')
    parser.add_argument('--repo', type=Path, default=HERE.parents[1])
    parser.add_argument('--export', action='store_true')
    args = parser.parse_args()
    for name in ('Arial.ttf', 'Arial Bold.ttf'):
        if not (args.font_dir / name).is_file():
            parser.error(f'Missing font: {args.font_dir / name}')

    def canvas(width, height, bg):
        im = Image.new('RGB', (width*SCALE, height*SCALE), bg)
        draw = ImageDraw.Draw(im)

        def label(x, y, value, size=16, color='#171717', bold=False, anchor='la'):
            font = ImageFont.truetype(str(args.font_dir / ('Arial Bold.ttf' if bold else 'Arial.ttf')), size*SCALE)
            draw.text((x*SCALE, y*SCALE), str(value), font=font, fill=color, anchor=anchor)

        def rect(x, y, w, h, color):
            draw.rectangle((x*SCALE, y*SCALE, (x+w)*SCALE, (y+h)*SCALE), fill=color)

        def line(points, color, width=1):
            draw.line([(x*SCALE, y*SCALE) for x, y in points], fill=color, width=width*SCALE)

        def dot(x, y, r, color):
            draw.ellipse(((x-r)*SCALE, (y-r)*SCALE, (x+r)*SCALE, (y+r)*SCALE), fill=color)
        return im, label, rect, line, dot

    def text(ident, x, y, w, h, value, size=18, color='#171717', bold=False):
        paragraphs = ''.join(f'<p><span style="font-size:{size}px;color:{color};font-weight:{700 if bold else 400}">{html.escape(row)}</span></p>' for row in value.split('\n'))
        return dict(elementId=ident, elementType='text', bounds=[x,y,w,h], content={
            'fontFamily':'Arial', 'align':['left','top'], 'text':paragraphs})

    def block(ident, x,y,w,h,color):
        return dict(elementId=ident, elementType='shape', bounds=[x,y,w,h], shapeName='rect', fill={'type':'solid','color':color})

    def figure(x,y,w,h):
        return dict(elementId='external-evidence', elementType='image', bounds=[x,y,w,h], src='media/evidence.png', fit={'mode':'contain'})

    projects = []

    def save(ident, category, bg, elements, im, data, purpose, adaptation):
        target = HERE / ident
        (target/'pages').mkdir(parents=True, exist_ok=True)
        (target/'media').mkdir(exist_ok=True)
        im.save(target/'media/evidence.png')
        manifest = {'version':'v2','title':purpose,'size':[960,540],'pages':['pages/01.page']}
        page = {'pageType':'content','background':{'type':'solid','color':bg},'elements':elements}
        for path, obj in [(target/'deck.pptd',manifest),(target/'pages/01.page',page),(target/'data.json',data)]:
            path.write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n')
        provenance = {'style':f'skills/ansatz-slide/reference/design_system/{category}/{ident}/design.md',
                      'purpose':purpose,'data_basis':data['basis'],'asset':'media/evidence.png',
                      'asset_author':'Original external figure generated by build.py using Pillow',
                      'native_elements':'Title, explanations, source/footer and structural rules remain editable',
                      'adaptation':adaptation,'font':'Arial, verified locally; not embedded or redistributed',
                      'scope':'One content-page pattern; not a complete deck or validation of every preset feature'}
        (target/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
        projects.append(ident)
        if args.export:
            subprocess.run(['node',str(args.repo/'bin/ansatz-slide.js'),'export',str(target),'-o',str(target/'demo.pptx')],check=True)

    # Consulting: original synthetic capability assessment, external stacked bars.
    im,L,R,ln,dot = canvas(510,235,'#2C2C2C')
    values = [('Tools',70),('Talent',45),('Governance',30)]
    for i,(name,value) in enumerate(values):
        y=15+i*76
        L(0,y,name,17,'#F3F3F3',True)
        R(0,y+29,440,29,'#345A4D'); R(0,y+29,440*value/100,29,'#36AA7E')
        L(10,y+33,f'{value}% ready',15,'#FFFFFF',True)
        L(448,y+33,'100%',12,'#B7B7B7')
    e=[block('kicker',48,27,144,24,'#125E42'),text('section',57,30,140,22,'01 / CAPABILITY',12,'#F3F3F3',True),
       text('title',48,72,865,55,'Governance is the first readiness gap',32,'#F3F3F3',True),
       text('basis',48,125,860,25,'Illustrative assessment / readiness score, 0–100 / not measured company data',15,'#B7B7B7'),
       block('divider',48,162,864,1,'#59665F'),figure(48,185,510,235),
       text('take1',603,190,305,47,'01  Tools lead at 70%',20,'#86C5AA',True),
       text('take2',603,247,305,62,'02  Talent needs a\n       practical training pilot',18,'#F3F3F3'),
       text('take3',603,323,305,68,'03  Agree ownership before\n       extending automation',18,'#F3F3F3'),
       block('conclusion-bg',48,443,864,43,'#0A3021'),text('conclusion',61,451,835,30,'Start with accountable decisions, then scale the tooling.',20,'#F3F3F3',True),
       text('source',48,507,800,20,'Source: data.json — synthetic scores for this layout demonstration.',11,'#B7B7B7'),text('page',878,507,45,20,'01 / 01',11,'#B7B7B7')]
    save('moss-green-transformation','consulting','#2C2C2C',e,im,{'basis':'Synthetic capability scores; no empirical claim','scores':dict(values)},'Prioritize governance before scaling','Single two-column chart page; no cover or deck-wide agenda.')

    # Finance: complete budget table rendered externally, never a native PPT table.
    im,L,R,ln,dot=canvas(570,260,'#FFFFFF')
    cols=[0,215,335,455]
    for x,name in zip(cols,['Cost line','Plan / kUSD','Actual / kUSD','Variance']): L(x,4,name,13,'#606060',True)
    ln([(0,32),(562,32)],'#0A0A0A')
    budget=[('Research',40,38),('Production',35,34),('Distribution',25,22)]
    for i,(name,plan,actual) in enumerate(budget):
        y=49+i*49
        L(0,y,name,18,'#3D3C3A'); L(298,y,plan,18,'#3D3C3A',anchor='ra'); L(426,y,actual,18,'#3D3C3A',anchor='ra'); L(558,y,f'{actual-plan:+d}',18,'#606060',anchor='ra')
        ln([(0,y+36),(562,y+36)],'#D6D6D6')
    L(0,210,'Total',18,'#0A0A0A',True); L(298,210,100,18,anchor='ra');L(426,210,94,18,anchor='ra');L(558,210,'-6',18,anchor='ra')
    e=[block('top-rule',52,27,856,2,'#0A0A0A'),text('title',52,53,856,50,'Delivery stays 6% below the planned budget',30,'#0A0A0A',True),
       text('basis',52,111,856,25,'Illustrative closed-period budget / kUSD / actual minus plan',15,'#606060'),
       block('divider',52,153,856,1,'#D6D6D6'),figure(52,179,570,260),block('rail',658,180,1,250,'#D6D6D6'),
       text('kpi',699,180,200,68,'94 kUSD',42,'#D6A000',True),text('kpi-basis',699,250,200,55,'Actual spend\n100 kUSD planned',17,'#606060'),
       text('implication',699,335,200,76,'Do not treat savings\nas proof of equal\noutput quality.',17,'#3D3C3A'),
       block('verdict',52,452,856,40,'#F0F0F0'),text('verdict-text',64,460,830,28,'Release the balance only after delivery-quality review.',19,'#0A0A0A',True),
       text('source',52,508,780,18,'Source: data.json — illustrative budget, not financial guidance.',11,'#606060'),text('page',867,508,45,18,'1 / 1',11,'#606060')]
    save('black-gold-ledger','finance','#FFFFFF',e,im,{'basis':'Synthetic closed-period budget in kUSD; not investment advice','rows':budget,'plan_total':100,'actual_total':94},'Budget evidence with explicit basis','White table-matrix page; no dark summary/closing sequence in this single-page sample.')

    # Work report: externally drawn, directly labelled series; actual/target explicit.
    im,L,R,ln,dot=canvas(590,265,'#06070B')
    counts=[30,33,38,42,48,52,58,60]
    for v in [15,30,45,60]: ln([(20,225-v*3),(580,225-v*3)],'#1A222C')
    ln([(20,225),(580,225)],'#536780')
    for i,v in enumerate(counts):
        x=34+i*69;R(x,225-v*3,38,v*3,'#1FB9D5');L(x+19,202-v*3,v,15,'#B8ECF9',True,'ma');L(x+19,237,f'W{i+1}',13,'#969DA3',anchor='ma')
    e=[text('ownership',57,22,500,22,'OPERATIONS / WEEKLY DELIVERY',12,'#969DA3'),text('report-id',774,22,150,22,'DEMO • 8 WEEKS',12,'#969DA3'),
       text('title',57,84,852,49,'Weekly throughput reaches the 60-item target',30,'#F7F8FA',True),text('basis',57,137,850,25,'Illustrative completed items / W1–W8 / constant counting rule',15,'#969DA3'),
       text('kpi',57,205,230,60,'100%',43,'#B8ECF9',True),text('kpi-basis',57,269,240,65,'W8 actual: 60 items\nW8 target: 60 items',18,'#C6CCD3'),
       text('caveat',57,350,245,70,'Throughput alone does\nnot establish quality\nor a causal improvement.',16,'#DFA93C'),figure(320,171,590,265),
       block('bottom-rule',57,461,846,1,'#1A222C'),text('conclusion',57,474,847,30,'Keep the target; add an independent quality check before scaling.',19,'#F7F8FA',True),
       text('source',57,518,780,18,'Source: data.json — synthetic weekly counts; no forecast shown.',10,'#969DA3'),text('page',859,518,60,18,'01 / 01',10,'#969DA3')]
    save('blue-flame-brand','work','#06070B',e,im,{'basis':'Synthetic weekly completed-item counts, W1-W8','actual':counts,'w8_target':60},'Throughput attainment with an explicit limitation','Single trend page without invented inflection causes; Arial used consistently.')

    # Promotion: seven-node pacing diagram is one external asset, not PPT drawing.
    im,L,R,ln,dot=canvas(800,195,'#F3E8D4')
    beats=['Brief','Make','Review','Tease','Launch','Listen','Learn']
    ln([(25,83),(775,83)],'#171717',2)
    for i,beat in enumerate(beats):
        x=25+i*125;color='#F05A39' if beat=='Launch' else '#2657D7' if beat=='Learn' else '#171717'
        dot(x,83,7,color);L(x,31,f'D{i*2+1:02}',17,color,True,'ma');L(x,111,beat,18,color,True,'ma')
    e=[text('title',80,63,810,66,'Build a launch that leaves room to learn.',34,'#171717',True),
       text('basis',80,143,800,32,'A proposed 13-day sequence — milestones, not measured campaign results.',16,'#625D54'),
       figure(80,206,800,195),text('conclusion',80,426,810,51,'The launch is a midpoint. Listening is part of the plan.',24,'#F05A39',True),
       text('source',80,511,735,18,'Source: data.json — original illustrative launch sequence.',11,'#625D54'),text('page',853,511,35,18,'01',11,'#171717')]
    save('cream-collage','promotion','#F3E8D4',e,im,{'basis':'Original illustrative 13-day plan, not historical results','beats':[{'day':i*2+1,'name':b} for i,b in enumerate(beats)]},'A campaign pacing page that includes learning','Seven-node timeline page, not a cover collage; no stock photos or decorative filler.')

    # Academic: analytic, reproducible plot, no fabricated experimental data.
    im,L,R,ln,dot=canvas(530,285,'#FCEEDC')
    def xy(x,y):return (265+x*104,236-y*47)
    ln([(30,236),(501,236)],'#172C34');ln([(265,18),(265,248)],'#172C34')
    for x in [-2,-1,0,1,2]:
        px,py=xy(x,0);ln([(px,py),(px,py+4)],'#172C34');L(px,246,x,12,'#172C34',anchor='ma')
    for y in [1,2,3,4]:
        px,py=xy(0,y);ln([(px-4,py),(px,py)],'#172C34');L(px-9,py-6,y,12,'#172C34',anchor='ra')
    ln([xy(-2+4*i/200,(-2+4*i/200)**2) for i in range(201)],'#0085FD',3)
    dot(*xy(0,0),5,'#0085FD'); L(350,35,'f(x) = x²',19,'#0085FD',True);L(503,243,'x',14);L(280,8,'f(x)',14)
    e=[text('title',27,24,908,57,'A positive quadratic has one global minimum',32,'#172C34',True),
       text('definition',35,143,340,42,'Let f(x) = x², x ∈ R.',25,'#172C34'),
       text('derivative',35,216,330,60,"f′(x) = 2x\nf′(0) = 0",26,'#0085FD',True),
       text('condition',35,318,325,64,'Here f(x) ≥ 0 everywhere;\nstationarity alone is not enough.',18,'#C32E8F'),figure(400,113,530,285),
       block('theorem-bg',35,438,895,57,'#F1F4F7'),text('theorem',50,449,862,37,'Since x² ≥ 0, equality occurs only at x = 0.',25,'#172C34',True),
       text('source',35,516,900,18,'Analytic example: y = x²; 201 plotting samples over [-2, 2]. Both axes dimensionless.',11,'#0085FD')]
    save('pastel-derivation','academic','#FFFFFF',e,im,{'basis':'Analytic identity f(x)=x^2, x real; no experimental or statistical claim','plot_domain':[-2,2],'samples':201},'Connect a derivative to the global minimum','Single schematic derivation; native Unicode equation text in Arial replaces unavailable upstream math fonts; no LaTeX-loader claim.')
    (HERE/'projects.json').write_text(json.dumps(projects,indent=2)+'\n')
    print(f'Built {len(projects)} projects.')


if __name__ == '__main__':
    main()
